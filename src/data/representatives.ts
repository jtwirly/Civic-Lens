export function findRepresentativeByPostalCode(postalCode: string): Representative | null {
  const clean = postalCode.trim().toUpperCase().replace(/\s+/g, '');
  if (!clean) return null;
  const prefix = clean.substring(0, 3);
  
  const match = CANADIAN_REPRESENTATIVES.find(rep => 
    rep.postalCodePrefixes.some(p => p.toUpperCase() === prefix)
  );
  
  // Return matched or default to Joël Lightbound (INDU Chair) if none found
  return match || CANADIAN_REPRESENTATIVES[0];
}
